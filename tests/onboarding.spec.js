test('authenticated owners cannot skip plan, configuration or import prerequisites', async ({ page }) => {
  await loginOwner(page)
  await page.goto(setup + '/welcome')
  await expect(page).toHaveURL(setup + '/plan')
  await page.getByRole('radio', { name: 'Free plan' }).check()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Connect Shopee (demo)' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Continue to Import' })).toBeDisabled()
  await configureStore(page)
  await page.getByRole('button', { name: 'Connect Shopee (demo)' }).click()
  await expect(page.getByRole('button', { name: 'Continue to Import' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Connect TikTok Shop (demo)' })).toBeDisabled()
  await page.getByRole('button', { name: 'Confirm Shopee demo shop' }).click()
  await page.getByRole('button', { name: 'Continue to Import' }).click()
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Start sync preview' }).click()
  await page.getByRole('button', { name: 'Simulate partial' }).click()
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Restart sync preview' }).click()
  await page.getByRole('button', { name: 'Simulate failed' }).click()
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Restart sync preview' }).click()
  await page.getByRole('button', { name: 'Simulate completed' }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page).toHaveURL(setup + '/welcome')
  await expect(page.getByText('New Studio', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Open demo dashboard', exact: true }).click()
  await expect(page).toHaveURL('/merchant/dashboard')
})

test('Pro plan changes, store edits, restart and reload invalidate dependent setup progress', async ({ page }) => {
  await toImport(page, 'Pro')
  await page.getByRole('link', { name: 'Back', exact: true }).click()
  await page.getByLabel('Store name', { exact: true }).fill('Changed Studio')
  await expect(page.getByRole('button', { name: 'Continue to Import' })).toBeDisabled()
  await page.getByRole('button', { name: 'Save store details', exact: true }).click()
  await expect(page.getByText('Not connected', { exact: true })).toHaveCount(2)
  await page.getByRole('link', { name: 'Back', exact: true }).click()
  await page.getByRole('radio', { name: 'Free plan' }).check()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByText('Not connected', { exact: true })).toHaveCount(2)
  await page.getByRole('button', { name: 'Restart preview' }).click()
  await expect(page).toHaveURL(setup + '/plan')
  await expect(page.getByRole('radio', { name: 'Free plan' })).not.toBeChecked()
  await page.getByRole('radio', { name: 'Pro plan' }).check()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.reload()
  await expect(page).toHaveURL(setup + '/plan')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL('/auth/login?setup=1')
  await page.goBack()
  await expect(page).toHaveURL('/auth/login?setup=1')
})

