test('Free restricts shops across marketplaces and requires explicit confirmation', async ({ page }) => {
  await toChannels(page)
  const next = page.getByRole('button', { name: 'Continue to Import' })
  await expect(next).toBeDisabled()
  await page.getByRole('button', { name: 'Connect Shopee (demo)' }).click()
  await expect(page.getByText('Awaiting confirmation · demo')).toBeVisible()
  await expect(next).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Connect TikTok Shop (demo)' })).toBeDisabled()
  await page.getByRole('button', { name: 'Confirm Shopee demo shop' }).click()
  await expect(next).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Connect TikTok Shop (demo)' })).toBeDisabled()
  await page.getByRole('button', { name: 'Remove Shopee demo shop' }).click()
  await expect(next).toBeDisabled()
  await page.getByRole('button', { name: 'Connect TikTok Shop (demo)' }).click()
  await page.getByRole('button', { name: 'Confirm TikTok Shop demo shop' }).click()
  await expect(page.getByRole('button', { name: 'Connect Shopee (demo)' })).toBeDisabled()
  await next.click()
  await expect(page.getByRole('heading', { name: 'Confirmed demo shops' }).locator('..')).toContainText('Sample TikTok Shop shop')
  await expect(page.getByText('Sample Shopee shop')).toHaveCount(0)
})

