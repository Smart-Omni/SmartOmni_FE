import { expect, test } from '@playwright/test'

const owner = '/auth/register/owner'
const setup = '/merchant/setup'
async function loginOwner(page) {
  await page.goto('/auth/login?setup=1')
  await page.getByLabel('Email address', { exact: true }).fill('owner@smartomni.demo')
  await page.getByLabel('Password', { exact: true }).fill('Demo@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(setup + '/plan')
}
async function configureStore(page) {
  await page.getByLabel('Store name', { exact: true }).fill('New Studio')
  await page.getByLabel('Target Domain', { exact: true }).fill('new-studio-preview')
  await page.getByRole('button', { name: 'Save store details', exact: true }).click()
}
async function toChannels(page, plan = 'Free') {
  await loginOwner(page)
  await page.getByRole('radio', { name: plan + ' plan' }).check()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page).toHaveURL(setup + '/channels')
  await configureStore(page)
}
async function toImport(page, plan = 'Free') {
  await toChannels(page, plan)
  await page.getByRole('button', { name: 'Connect Shopee (demo)', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm Shopee demo shop', exact: true }).click()
  await page.getByRole('button', { name: 'Continue to Import' }).click()
}

test('tenant account registration ends at success preview then requires sign in before setup', async ({ page }) => {
  const posts = []
  page.on('request', request => { if (request.method() === 'POST') posts.push(request.url()) })
  await page.goto(owner)
  await expect(page.locator('form input')).toHaveCount(4)
  await expect(page.getByRole('navigation', { name: 'Owner onboarding progress' })).toHaveCount(0)
  await expect(page.getByLabel('Store name', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Target Domain', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByLabel('Full name', { exact: true })).toBeFocused()
  await page.getByLabel('Full name', { exact: true }).fill('New Owner')
  await page.getByLabel('Email address', { exact: true }).fill('new-owner@example.com')
  await page.getByLabel('Password', { exact: true }).fill('example-secret')
  await page.getByLabel('Confirm password', { exact: true }).fill('different')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByText('Passwords do not match. Enter the same password.')).toBeVisible()
  await page.getByLabel('Confirm password', { exact: true }).fill('example-secret')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your next step: Sign in.')
  await expect(page).toHaveURL(owner)
  await expect(page.getByRole('link', { name: 'Continue to sign in', exact: true })).toBeVisible()
  expect(await page.getByRole('link', { name: 'Continue to sign in', exact: true }).evaluate(element => getComputedStyle(element).color)).toBe('rgb(255, 255, 255)')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/tenant-registration/registration-complete.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))).toEqual({ local: {}, session: {} })
  expect(posts).toEqual([])
  await page.getByRole('button', { name: 'Back to registration', exact: true }).click()
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('')
  await page.getByRole('link', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL('/auth/login?setup=1')
  await expect(page.getByRole('heading', { name: 'Welcome back.', exact: true })).toBeVisible()
  await page.getByLabel('Email address', { exact: true }).fill('owner@smartomni.demo')
  await page.getByLabel('Password', { exact: true }).fill('Demo@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(setup + '/plan')
  await expect(page.getByRole('navigation', { name: 'Owner onboarding progress' }).getByText('Basic information')).toHaveCount(0)
  await expect(page.getByRole('progressbar', { name: 'Onboarding step', includeHidden: true })).toHaveAttribute('aria-valuemax', '4')
})

