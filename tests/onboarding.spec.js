for (const outcome of ['partial', 'failed']) {
  test(`${outcome} sync scenario keeps Welcome locked`, async ({ page }) => {
    await toImport(page)
    const next = page.getByRole('button', { name: 'Continue', exact: true })
    await expect(next).toBeDisabled()
    await page.getByRole('button', { name: 'Start sync preview' }).click()
    await expect(page.getByRole('status')).toContainText('In progress')
    await expect(next).toBeDisabled()
    await page.getByRole('button', { name: `Simulate ${outcome}` }).click()
    await expect(next).toBeDisabled()
    await expect(page.getByRole('link', { name: /^5Welcome$/ })).toHaveCount(0)
    if (outcome === 'partial') {
      await expect(page.getByText('Sample records succeeded', { exact: true }).locator('..')).toContainText('8')
      await expect(page.getByText('Sample records needing attention', { exact: true }).locator('..')).toContainText('4')
    }
    await page.getByRole('button', { name: 'Restart sync preview' }).click()
    await page.getByRole('button', { name: 'Simulate completed' }).click()
    await expect(next).toBeEnabled()
  })
}

test('completed preview opens Welcome but never authenticates or grants Dashboard access', async ({ page }) => {
  const requests = []
  const errors = []
  page.on('request', request => { if (request.method() === 'POST') requests.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await toImport(page)
  await page.getByRole('button', { name: 'Start sync preview' }).click()
  await page.getByRole('button', { name: 'Simulate completed' }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page).toHaveURL(`${owner}/welcome`)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Welcome to SmartOmni.')
  await expect(page.getByText('WELCOME PREVIEW · NO REAL WORKSPACE CREATED')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Go to Dashboard' })).toBeDisabled()
  await expect(page.getByText(/No account, Tenant, subscription, marketplace connection/)).toBeVisible()
  expect(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage }, cookies: document.cookie }))).toEqual({ local: {}, session: {}, cookies: '' })
  expect(requests).toEqual([])
  expect(errors).toEqual([])
  // An old browser-history Welcome entry must not bypass a new pending import.
  await page.goBack()
  await page.getByRole('button', { name: 'Restart sync preview' }).click()
  await page.goForward()
  await expect(page).toHaveURL(`${owner}/import`)
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled()
})

test('upstream edits, restart, refresh, and leaving the wizard invalidate demo progress', async ({ page }) => {
  await toImport(page)
  await page.getByRole('button', { name: 'Start sync preview' }).click()
  await page.getByRole('button', { name: 'Simulate completed' }).click()
  await page.getByRole('link', { name: 'Back', exact: true }).click()
  await page.getByRole('button', { name: 'Remove Shopee demo shop' }).click()
  await page.getByRole('button', { name: 'Connect Shopee (demo)' }).click()
  await page.getByRole('button', { name: 'Confirm Shopee demo shop' }).click()
  await page.getByRole('button', { name: 'Continue to Import' }).click()
  await expect(page).toHaveURL(`${owner}/import`)
  await expect(page.getByRole('region', { name: 'Synchronization preview' }).getByRole('status')).toContainText('Not started')
  await page.getByRole('button', { name: 'Restart preview' }).click()
  await expect(page).toHaveURL(owner)
  await expect(page.getByLabel('Full name')).toHaveValue('')
  await fillOwner(page)
  await page.getByRole('button', { name: 'Continue to Plans' }).click()
  await page.reload()
  await expect(page).toHaveURL(owner)
  await expect(page.getByLabel('Store name')).toHaveValue('')
  await fillOwner(page)
  await page.getByRole('button', { name: 'Continue to Plans' }).click()
  await page.getByRole('link', { name: 'Back to Account Type' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('How will you use SmartOmni?')
  await page.goBack()
  await expect(page).toHaveURL(owner)
  await expect(page.getByLabel('Email address')).toHaveValue('')
})

