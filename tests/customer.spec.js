import { expect, test } from '@playwright/test'

async function login(page, email = 'customer@smartomni.demo', password = 'Demo@123') {
  await page.goto('/auth/login?account=customer')
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL('/store/everyday-studio')
  await page.getByRole('navigation', { name: 'Store account' }).getByRole('link', { name: 'My membership', exact: true }).click()
  await expect(page).toHaveURL('/customer')
}

test('customer claims once, sees updated points, filters history and signs out', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page)
  await expect(page.getByLabel('Loyalty points')).toContainText('1,250')
  await page.getByRole('link', { name: 'Claim order points', exact: true }).last().click()
  const input = page.getByLabel('Order ID', { exact: false })
  for (const [id, message] of [['ESO-1049', 'in transit'], ['ESO-1050', 'cancelled'], ['ESO-1051', 'could not find'], ['ESO-1042', 'already been claimed']]) {
    await input.fill(id)
    await page.getByRole('button', { name: 'Check eligibility' }).click()
    await expect(page.getByRole('alert')).toContainText(message)
    await expect(page.getByRole('button', { name: 'Confirm claim' })).toHaveCount(0)
  }
  await input.fill('eso-1048')
  await page.getByRole('button', { name: 'Check eligibility' }).click()
  await expect(page.getByRole('status')).toContainText('Eligible for points')
  await page.getByRole('button', { name: 'Confirm claim' }).click()
  await expect(page.getByRole('status')).toContainText('+65 points')
  await page.getByRole('link', { name: 'View my membership' }).click()
  await expect(page.getByLabel('Loyalty points')).toContainText('1,315')
  await page.reload()
  await expect(page.getByLabel('Loyalty points')).toContainText('1,315')
  await page.getByRole('link', { name: 'Claim history', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search claim history' }).fill('1048')
  await page.getByRole('button', { name: 'View claim ESO-1048' }).click()
  await expect(page.getByRole('dialog')).toContainText('+65 points')
  await page.getByRole('button', { name: 'Close details' }).click()
  await page.getByRole('tab', { name: 'TikTok Shop' }).click()
  await expect(page.getByRole('heading', { name: 'No matching claims' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByRole('button', { name: /View claim/ })).toHaveCount(4)
  await page.getByRole('link', { name: 'Claim order points', exact: true }).click()
  await input.fill('ESO-1048')
  await page.getByRole('button', { name: 'Check eligibility' }).click()
  await expect(page.getByRole('alert')).toContainText('already been claimed')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL('/store/everyday-studio')
  await page.goto('/customer/history')
  await expect(page).toHaveURL('/auth/login?account=customer')
  expect(errors).toEqual([])
})

test('registration requires verification and new members start empty', async ({ page }) => {
  await page.goto('/store/everyday-studio')
  await page.getByRole('navigation', { name: 'Store account' }).getByRole('link', { name: 'Sign up', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Create your customer account.' })).toBeVisible()
  await page.getByLabel('Full name').fill('Alex Customer')
  await page.getByLabel('Email address').fill('alex.customer@example.com')
  await page.getByLabel('Password', { exact: true }).fill('Local@123')
  await page.getByLabel('Confirm password', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByLabel('Confirm password', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Confirm password', { exact: true }).fill('Local@123')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL('/customer/verify-email')
  await page.getByRole('link', { name: 'Back to sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  await page.getByLabel('Email address').fill('alex.customer@example.com')
  await page.getByLabel('Password', { exact: true }).fill('Local@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Verify your email')
  await page.getByRole('link', { name: 'Verify your email address' }).click()
  await page.getByRole('button', { name: 'Resend verification link' }).click()
  await page.getByRole('link', { name: 'Open demo verification link' }).click()
  await page.getByRole('button', { name: 'Verify email address' }).click()
  await expect(page).toHaveURL('/store/everyday-studio')
  await expect(page.getByRole('navigation', { name: 'Store account' })).toContainText('Alex Customer')
  await page.getByRole('link', { name: 'My membership', exact: true }).click()
  await expect(page.getByLabel('Loyalty points')).toContainText('0')
  await expect(page.getByRole('heading', { name: 'No claims yet' })).toBeVisible()
  const storage = await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))
  expect(storage).not.toContain('Local@123')
})

test('reset is one-use and the new password works in this SPA session', async ({ page }) => {
  await page.goto('/customer/login')
  await page.getByRole('button', { name: 'Forgot password?' }).click()
  await expect(page.getByRole('heading', { name: 'Forgot your password?' })).toBeVisible()
  await page.getByLabel('Email address').fill('customer@smartomni.demo')
  await page.getByRole('button', { name: 'Request reset link' }).click()
  await page.getByRole('link', { name: 'Open demo reset link' }).click()
  const resetUrl = page.url()
  await page.getByLabel('Password', { exact: true }).fill('Changed@123')
  await page.getByLabel('Confirm password', { exact: true }).fill('Changed@123')
  await page.getByRole('button', { name: 'Save new password' }).click()
  await page.getByRole('link', { name: 'Continue to sign in' }).click()
  await page.getByLabel('Email address').fill('customer@smartomni.demo')
  await page.getByLabel('Password', { exact: true }).fill('Changed@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL('/store/everyday-studio')
  await page.getByRole('link', { name: 'My membership', exact: true }).click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.goto(resetUrl)
  await page.getByLabel('Password', { exact: true }).fill('Another@123')
  await page.getByLabel('Confirm password', { exact: true }).fill('Another@123')
  await page.getByRole('button', { name: 'Save new password' }).click()
  await expect(page.getByRole('alert')).toContainText('invalid or expired')
})

test('customer cannot open merchant or admin tools, and shared sign in routes correctly', async ({ page }) => {
  await page.goto('/auth/login')
  await page.getByLabel('Email address').fill('customer@smartomni.demo')
  await page.getByLabel('Password', { exact: true }).fill('Demo@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL('/store/everyday-studio')
  for (const route of ['/merchant/dashboard', '/merchant/vouchers', '/admin']) {
    await page.goto(route)
    await expect(page).toHaveURL('/customer')
    await expect(page.getByRole('heading', { name: 'Your everyday, rewarded.' })).toBeVisible()
  }
})

for (const width of [375, 768, 1440]) {
  test(`Customer screens fit at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    for (const route of ['/auth/register/customer', '/customer/login', '/customer/verify-email', '/customer/reset-password']) {
      await page.goto(route)
      await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      if (route === '/auth/register/customer') await page.screenshot({ path: `artifacts/customer/register-${width}.png`, fullPage: true, animations: 'disabled' })
    }
    await login(page)
    for (const route of ['/customer', '/customer/claim', '/customer/history']) {
      await page.goto(route)
      await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `artifacts/customer/${route.split('/').pop()}-${width}.png`, fullPage: true })
    }
  })
}

for (const width of [375, 1440]) {
  test(`landing and guest storefront use shared sign in at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await page.getByRole('banner').getByRole('link', { name: 'Sign in', exact: true }).filter({ visible: true }).first().click()
    await expect(page).toHaveURL('/auth/login')
    await page.getByLabel('Email address').fill('customer@smartomni.demo')
    await page.getByLabel('Password', { exact: true }).fill('Demo@123')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page).toHaveURL('/store/everyday-studio')
    const accountNav = page.getByRole('navigation', { name: 'Store account' })
    await expect(accountNav).toContainText('Minh Anh')
    await expect(accountNav.getByRole('link', { name: 'Sign in', exact: true })).toHaveCount(0)
    await page.reload()
    await expect(accountNav).toContainText('Minh Anh')
    await page.getByRole('banner').screenshot({ path: `artifacts/customer/store-customer-${width}.png` })
    await accountNav.getByRole('button', { name: 'Sign out', exact: true }).click()
    await expect(accountNav.getByRole('link', { name: 'Sign up', exact: true })).toBeVisible()
    await page.getByRole('banner').screenshot({ path: `artifacts/customer/store-guest-${width}.png` })
    await accountNav.getByRole('link', { name: 'Sign in', exact: true }).click()
    await expect(page).toHaveURL('/auth/login?account=customer')
    await page.getByRole('link', { name: 'Create account', exact: true }).click()
    await expect(page).toHaveURL('/auth/register/customer')
    await expect(page.getByRole('form', { name: 'Customer registration' })).toBeVisible()
    await page.getByRole('link', { name: 'Sign in', exact: true }).click()
    await expect(page).toHaveURL('/auth/login?account=customer')
    await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
    await page.getByLabel('Email address').fill('customer@smartomni.demo')
    await page.getByLabel('Password', { exact: true }).fill('Demo@123')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page).toHaveURL('/store/everyday-studio')
    await expect(accountNav).toContainText('Minh Anh')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
