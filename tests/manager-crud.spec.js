import { expect, test } from '@playwright/test'

async function login(page, role = 'owner') {
  await page.goto('/auth/login')
  await page.getByLabel('Email address').fill(`${role}@smartomni.demo`)
  await page.getByLabel('Password', { exact: true }).fill('Demo@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/merchant\/dashboard$/)
}
async function createManager(page, email, name) {
  const form = page.getByRole('form', { name: 'Invite manager' })
  await form.getByLabel('Full name', { exact: true }).fill(name)
  await form.getByLabel('Manager email').fill(email)
  await form.getByLabel('Phone number').fill('+84 901 234 567')
  await form.getByLabel('Job title').fill('Store associate')
  await form.getByLabel('Internal notes').fill('Morning shift')
  await form.getByRole('button', { name: 'Create demo invitation' }).click()
  await expect(form.getByLabel('Manager email')).toHaveValue('')
}
const row = (page, email) => page.getByRole('listitem').filter({ hasText: email })

test('manager CRUD persists profile changes, supports search and filters, and deletes directory records', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page)
  await page.goto('/merchant/team')
  await createManager(page, 'person@example.com', 'Morgan Tran')
  await row(page, 'person@example.com').getByRole('button', { name: 'View details' }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Morgan Tran')
  await expect(dialog).toContainText('+84 901 234 567')
  await expect(dialog).toContainText('Morning shift')
  await dialog.getByRole('button', { name: 'Edit manager', exact: true }).click()
  await dialog.getByLabel('Full name', { exact: true }).fill('Discarded name')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(row(page, 'person@example.com')).toContainText('Morgan Tran')
  await row(page, 'person@example.com').getByRole('button', { name: 'Edit manager', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Full name', { exact: true }).fill('Morgan Le')
  await dialog.getByLabel('Manager email').fill('morgan@example.com')
  await dialog.getByLabel('Phone number').fill('0909998888')
  await dialog.getByLabel('Job title').fill('Inventory specialist')
  await dialog.getByLabel('Internal notes').fill('Afternoon shift\nTrained on inventory')
  await dialog.getByLabel('View inventory alerts').check()
  await dialog.getByRole('button', { name: 'Save manager changes' }).click()
  await expect(row(page, 'person@example.com')).toHaveCount(0)
  await page.reload()
  await expect(row(page, 'morgan@example.com')).toContainText('Morgan Le')
  await page.getByLabel('Search manager').fill('INVENTORY SPECIALIST')
  await expect(row(page, 'morgan@example.com')).toBeVisible()
  await page.getByLabel('Manager status').selectOption('ACTIVE')
  await expect(page.getByRole('heading', { name: 'No managers match these filters.' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByLabel('Search manager').fill('0909998888')
  await row(page, 'morgan@example.com').getByRole('button', { name: 'View details' }).click()
  await expect(page.getByRole('dialog')).toContainText('Trained on inventory')
  await page.getByRole('dialog').getByRole('button', { name: 'Done', exact: true }).click()
  await row(page, 'morgan@example.com').getByRole('button', { name: 'Delete manager record' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(row(page, 'morgan@example.com')).toBeVisible()
  await row(page, 'morgan@example.com').getByRole('button', { name: 'Delete manager record' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete manager record', exact: true }).click()
  await expect(row(page, 'morgan@example.com')).toHaveCount(0)
  await page.reload()
  await expect(page.getByText('No manager invitations yet.', { exact: false })).toBeVisible()
  expect(errors).toEqual([])
})

test('active profile edits update the manager session and deleting an active record removes access immediately', async ({ page, context }) => {
  await login(page)
  await page.goto('/merchant/team')
  await createManager(page, 'manager@smartomni.demo', 'Jamie Nguyen')
  const manager = await context.newPage()
  await login(manager, 'manager')
  await manager.goto('/merchant/notifications')
  await manager.getByRole('button', { name: 'Accept demo invitation' }).click()
  await manager.goto('/merchant/profile')
  await expect(manager.getByText('Jamie Nguyen', { exact: true })).toBeVisible()
  await row(page, 'manager@smartomni.demo').getByRole('button', { name: 'Edit manager', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Manager email')).toHaveAttribute('readonly', '')
  await dialog.getByLabel('Full name', { exact: true }).fill('Jamie Updated')
  await dialog.getByRole('button', { name: 'Save manager changes' }).click()
  await expect(manager.getByText('Jamie Updated', { exact: true })).toBeVisible()
  await manager.goto('/merchant/dashboard')
  await expect(manager.getByRole('heading', { name: 'Recent orders' })).toBeVisible()
  await row(page, 'manager@smartomni.demo').getByRole('button', { name: 'Delete manager record' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete manager record', exact: true }).click()
  await expect(manager.getByRole('heading', { name: 'Your workspace is waiting.' })).toBeVisible()
  await manager.reload()
  await expect(manager.getByRole('heading', { name: 'Recent orders' })).toHaveCount(0)
  await createManager(page, 'manager@smartomni.demo', 'Reinvited Jamie')
  await manager.goto('/merchant/notifications')
  await expect(manager.getByRole('button', { name: 'Accept demo invitation' })).toBeVisible()
})

test('stale manager edits and deletion confirmations cannot overwrite changes from another owner tab', async ({ page, context }) => {
  await login(page)
  await page.goto('/merchant/team')
  await createManager(page, 'person@example.com', 'Morgan Tran')
  const other = await context.newPage()
  await login(other)
  await other.goto('/merchant/team')
  await row(page, 'person@example.com').getByRole('button', { name: 'Edit manager', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Job title').fill('Stale job title')
  await row(other, 'person@example.com').getByRole('button', { name: 'Edit manager', exact: true }).click()
  await other.getByRole('dialog').getByLabel('Job title').fill('Current job title')
  await other.getByRole('dialog').getByRole('button', { name: 'Save manager changes' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Save manager changes' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('changed in another tab')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(row(page, 'person@example.com')).toContainText('Current job title')
  await row(page, 'person@example.com').getByRole('button', { name: 'Delete manager record' }).click()
  await row(other, 'person@example.com').getByRole('button', { name: 'Edit manager', exact: true }).click()
  await other.getByRole('dialog').getByLabel('Internal notes').fill('Keep this latest note')
  await other.getByRole('dialog').getByRole('button', { name: 'Save manager changes' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete manager record', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('changed in another tab')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(row(page, 'person@example.com')).toBeVisible()
})

test('manager validation, duplicate email checks and failed deletion preserve existing records', async ({ page }) => {
  await login(page)
  await page.goto('/merchant/team')
  await createManager(page, 'one@example.com', 'First person')
  await createManager(page, 'two@example.com', 'Second person')
  await row(page, 'two@example.com').getByRole('button', { name: 'Edit manager', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Manager email').fill(' ONE@EXAMPLE.COM ')
  await dialog.getByRole('button', { name: 'Save manager changes' }).click()
  await expect(dialog.getByRole('alert')).toContainText('already has a manager record')
  await dialog.getByLabel('Manager email').fill('two@example.com')
  await dialog.getByLabel('View orders', { exact: true }).uncheck()
  await dialog.getByRole('button', { name: 'Save manager changes' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Select at least one permission')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await row(page, 'one@example.com').getByRole('button', { name: 'Delete manager record' }).click()
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Storage unavailable') } })
  await page.getByRole('dialog').getByRole('button', { name: 'Delete manager record', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Could not save')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(row(page, 'one@example.com')).toBeVisible()
})

test('legacy manager records can be edited and revoked records can be deleted', async ({ page }) => {
  await login(page)
  await page.evaluate(() => localStorage.setItem('smartomni.team-demo.v1', JSON.stringify([{ id: 'legacy-manager', email: 'manager@smartomni.demo', status: 'INVITED', permissions: ['orders:read'], invitedAt: '2026-10-20T08:00:00.000Z' }])))
  await page.goto('/merchant/team')
  await row(page, 'manager@smartomni.demo').getByRole('button', { name: 'Edit manager', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Full name', { exact: true })).toHaveValue('Jamie Nguyen')
  await dialog.getByLabel('Job title').fill('Store associate')
  await dialog.getByRole('button', { name: 'Save manager changes' }).click()
  await expect(row(page, 'manager@smartomni.demo')).toContainText('Jamie Nguyen')
  await row(page, 'manager@smartomni.demo').getByRole('button', { name: 'Revoke invitation' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Revoke invitation', exact: true }).click()
  await expect(row(page, 'manager@smartomni.demo').getByRole('button', { name: 'Edit manager', exact: true })).toHaveCount(0)
  await row(page, 'manager@smartomni.demo').getByRole('button', { name: 'Delete manager record' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete manager record', exact: true }).click()
  await expect(row(page, 'manager@smartomni.demo')).toHaveCount(0)
})

