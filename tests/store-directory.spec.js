import { expect, test } from '@playwright/test'

test.use({ viewport: { width: 1440, height: 1000 } })

test('guest can browse, filter, search a subdomain and recover from no results', async ({ page }) => {
  await page.goto('/stores')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('A little discovery.Your kind of store.')
  const cards = page.getByRole('link', { name: /^Visit / })
  await expect(cards).toHaveCount(6)
  await expect(page.getByText('Northline Goods', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Little Leaf', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Home & living 2' }).click()
  await expect(cards).toHaveCount(2)
  await page.reload()
  await expect(cards).toHaveCount(2)
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByRole('searchbox', { name: 'Search stores' }).fill('paper-house.smartomni.example')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(cards).toHaveCount(1)
  await expect(cards).toHaveAttribute('href', '/store/paper-house')
  await page.getByRole('searchbox', { name: 'Search stores' }).fill('no-such-store')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No stores found.' })).toBeVisible()
  await page.getByRole('button', { name: 'Show all stores' }).click()
  await expect(cards).toHaveCount(6)
})

test('each storefront opens directly and restricts product links to its own catalog', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  for (const slug of ['moss-and-clay', 'sunday-supply', 'form-and-function', 'daybreak-coffee', 'paper-house']) {
    await page.goto(`/store/${slug}`)
    await expect(page.getByText(`${slug}.smartomni.example`, { exact: true })).toBeVisible()
    await expect(page.getByRole('region', { name: 'Products' }).getByRole('article').first()).toBeVisible()
    await expect(page.getByRole('link', { name: 'Ask product assistant', exact: true })).toHaveAttribute('href', `/store/${slug}/assistant`)
  }
  await page.goto('/store/moss-and-clay/products/wireless-mouse')
  await expect(page.getByRole('heading', { name: 'Product not found.' })).toBeVisible()
  await page.goto('/store/moss-and-clay/products/ceramic-cup')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Ceramic Coffee Cup')
  await expect(page.getByRole('region', { name: 'About this storefront' })).toContainText('Moss & Clay')
  await page.goto('/store/moss-and-clay/flash-sale')
  await expect(page.getByRole('region', { name: 'Sale products' }).getByRole('article')).toHaveCount(3)
  expect(errors).toEqual([])
})

test('AI entry selects a store and conversation stays in that shop', async ({ page }) => {
  await page.goto('/stores')
  await page.getByRole('button', { name: 'Ask in this store Everyday Studio' }).click()
  await page.getByRole('menuitem', { name: 'Moss & Clay', exact: true }).click()
  await page.getByRole('link', { name: 'Ask product assistant', exact: true }).click()
  await expect(page).toHaveURL(/store\/moss-and-clay\/assistant$/)
  await page.getByLabel('Your question').fill('under 500000')
  await page.getByRole('button', { name: 'Ask assistant', exact: true }).click()
  await expect(page.getByRole('log')).toContainText('Ceramic Coffee Cup')
  await expect(page.getByRole('log')).not.toContainText('Wireless Mouse')
  await page.reload()
  await expect(page.getByRole('log')).toContainText('under 500000')
  await page.goto('/store/paper-house/assistant')
  await expect(page.getByRole('log')).not.toContainText('under 500000')
  await page.getByLabel('Your question').fill('under 500000')
  await page.getByRole('button', { name: 'Ask assistant', exact: true }).click()
  await expect(page.getByRole('log')).toContainText('Wireless Mouse')
  await expect(page.getByRole('log')).not.toContainText('Ceramic Coffee Cup')
})

test('saved products, recently viewed and reviews remain separated between shops', async ({ page }) => {
  await page.goto('/store/moss-and-clay/products/desk-light')
  await expect(page.getByRole('heading', { name: 'Product not found.' })).toBeVisible()
  await page.goto('/store/paper-house/products/desk-light')
  await page.getByRole('button', { name: 'Save Slim Desk Light', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Saved products (1)' })).toBeVisible()
  await page.goto('/store/everyday-studio?saved=1')
  await expect(page.getByRole('heading', { name: 'No saved products yet.' })).toBeVisible()
  await page.goto('/store/paper-house?saved=1')
  await expect(page.getByRole('region', { name: 'Products' })).toContainText('Slim Desk Light')
  await expect(page.getByRole('heading', { name: 'Recently viewed', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('smartomni:paper-house:recently-viewed')))).toContain('desk-light')
  expect(await page.evaluate(() => localStorage.getItem('smartomni:everyday-studio:recently-viewed'))).toBeNull()
  await page.evaluate(() => localStorage.setItem('smartomni:paper-house:reviews:desk-light', JSON.stringify([{ name: 'Guest shopper', text: 'A great light for my workspace.', rating: 5, createdAt: '2026-10-27' }])))
  await page.goto('/store/paper-house/products/desk-light')
  await expect(page.getByText('1 review', { exact: true })).toBeVisible()
  await page.goto('/store/everyday-studio/products/desk-light')
  await expect(page.getByText('0 reviews', { exact: true })).toBeVisible()
})

test('unavailable shops disappear from the directory and direct links recover safely', async ({ page }) => {
  await page.goto('/stores')
  await page.evaluate(() => {
    localStorage.setItem('smartomni.platform-demo.v1', JSON.stringify({ tenants: [{ id: 'tenant-02', status: 'SUSPENDED' }] }))
    window.dispatchEvent(new Event('smartomni:platform-demo'))
  })
  await expect(page.getByRole('link', { name: 'Visit Moss & Clay' })).toHaveCount(0)
  await page.goto('/store/moss-and-clay/assistant')
  await expect(page.getByRole('heading', { name: 'Store not found.' })).toBeVisible()
  await page.getByRole('link', { name: 'Explore stores', exact: true }).click()
  await expect(page).toHaveURL(/\/stores$/)
  await page.goto('/store/unknown-shop')
  await expect(page.getByRole('heading', { name: 'Store not found.' })).toBeVisible()
})

test('desktop layouts keep AI action readable, shop names visible and no horizontal overflow', async ({ page }) => {
  for (const width of [1024, 1280, 1440, 1920]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/stores')
    const action = page.getByRole('link', { name: 'Ask product assistant', exact: true })
    await expect(action).toBeVisible()
    expect(await action.evaluate(element => getComputedStyle(element).color)).toBe('rgb(255, 255, 255)')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await expect(page.getByRole('link', { name: 'Visit Form & Function — Home and Everyday Essentials', exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Ask in this store Everyday Studio' }).click()
  await expect(page.getByRole('menuitem', { name: 'Form & Function — Home and Everyday Essentials', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
})
