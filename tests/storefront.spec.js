for (const width of [320, 375, 768, 1024, 1440]) {
  test(`catalog and detail fit at ${width}px, with no filter sidebar`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(store)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    const fits = () => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)
    expect(await fits()).toBe(true)
    await expect(page.locator('header').getByRole('link', { name: /^(Shop|About)$/ })).toHaveCount(0)
    const headerSearch = page.locator('header').getByRole('search')
    await expect(headerSearch).toBeVisible()
    await headerSearch.getByRole('searchbox').focus()
    await expect(headerSearch.getByRole('searchbox')).toBeFocused()
    expect(await fits()).toBe(true)
    await page.screenshot({ path: `artifacts/storefront/search-${width}.png`, animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(headerSearch).toBeVisible()
    await expect(page.getByRole('complementary', { name: 'Catalog filters' })).toHaveCount(0)
    await page.goto(`${store}/products/wireless-mouse?sku=WM-WHT`)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Wireless Mouse')
    expect(await fits()).toBe(true)
    await page.screenshot({ path: `artifacts/storefront/detail-${width}.png`, fullPage: true, animations: 'disabled' })
    await page.goto(store)
    await page.getByRole('region', { name: 'Products' }).getByRole('article').last().scrollIntoViewIfNeeded()
    await page.getByRole('link', { name: 'SmartOmni Storefront home' }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: `artifacts/storefront/catalog-${width}.png`, fullPage: true, animations: 'disabled' })
  })
}

