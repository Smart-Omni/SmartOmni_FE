test('view history persists on the storefront without a recently viewed section on product detail', async ({ page }) => {
  await page.goto(`${store}/products/wireless-mouse`)
  const recent = page.getByRole('region', { name: 'Recently viewed', exact: true })
  await expect(recent).toHaveCount(0)
  await page.evaluate(() => localStorage.setItem('smartomni:everyday-studio:recently-viewed', '{bad json'))
  await page.reload()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('smartomni:everyday-studio:recently-viewed'))).toContain('wireless-mouse')
  await page.goto(`${store}/products/studio-headphones`)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Studio Headphones')
  await expect.poll(() => page.evaluate(() => localStorage.getItem('smartomni:everyday-studio:recently-viewed'))).toContain('studio-headphones')
  await expect(recent).toHaveCount(0)
  await page.goto(`${store}/products/wireless-mouse?sku=WM-BLK`)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Wireless Mouse')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('smartomni:everyday-studio:recently-viewed'))[0])).toBe('wireless-mouse')
  await page.goto(`${store}?category=workspace`)
  await expect(recent.getByRole('article')).toHaveCount(2)
  await expect(recent.getByRole('article').first()).toContainText('Wireless Mouse')
  await page.reload()
  await expect(recent.getByRole('article')).toHaveCount(2)
  const section = await recent.boundingBox()
  const footer = await page.locator('footer').boundingBox()
  expect(section.y + section.height).toBeLessThanOrEqual(footer.y)
})
test('recently viewed shows the latest ten in a compact scrollable row', async ({ page }) => {
  await page.goto(store)
  const ids = ['ceramic-cup', 'classic-watch', 'canvas-backpack', 'court-sneakers', 'cotton-tee', 'shoulder-bag', 'running-shoes', 'accent-chair', 'wireless-mouse', 'studio-headphones', 'desk-light', 'mechanical-keyboard']
  await page.evaluate(ids => localStorage.setItem('smartomni:everyday-studio:recently-viewed', JSON.stringify(ids)), ids)
  await page.reload()
  const recent = page.getByRole('region', { name: 'Recently viewed', exact: true })
  await expect(recent.getByRole('article')).toHaveCount(10)
  await expect(recent.getByRole('article').first()).toContainText('Ceramic Coffee Cup')
  await expect(recent.getByRole('article').last()).toContainText('Studio Headphones')
  for (const width of [1440, 375]) {
    await page.setViewportSize({ width, height: 900 })
    await recent.scrollIntoViewIfNeeded()
    const first = await recent.getByRole('article').first().boundingBox()
    const last = await recent.getByRole('article').last().boundingBox()
    expect(last.y).toBe(first.y)
    expect(first.width).toBeLessThan(120)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await recent.screenshot({ path: `artifacts/storefront-recent/compact-${width}.png` })
  }
  await recent.getByRole('link', { name: 'View Classic Analog Watch', exact: true }).click()
  await expect(recent).toHaveCount(0)
  await page.goto(store)
  await expect(recent.getByRole('article')).toHaveCount(10)
  await expect(recent.getByRole('article').first()).toContainText('Classic Analog Watch')
})

test('saved products persist and stay synchronized with the header heart', async ({ page }) => {
  await page.goto(store)
  const header = page.locator('header').first()
  await expect(header.getByRole('link', { name: 'SmartOmni Storefront home' }).locator('span')).toHaveCSS('font-family', /Brolink/)
  await page.getByRole('button', { name: 'Save Wireless Mouse', exact: true }).click()
  await expect(header.getByRole('link', { name: 'Saved products (1)', exact: true })).toBeVisible()
  await page.goto(`${store}/products/studio-headphones`)
  await page.getByRole('button', { name: 'Save Studio Headphones', exact: true }).click()
  await header.getByRole('link', { name: 'Saved products (2)', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Saved products')
  const grid = page.getByRole('region', { name: 'Products', exact: true })
  await expect(grid.getByRole('article')).toHaveCount(2)
  await page.reload()
  await expect(grid.getByRole('article')).toHaveCount(2)
  await page.getByRole('button', { name: 'Unsave Wireless Mouse', exact: true }).click()
  await expect(grid.getByRole('article')).toHaveCount(1)
  await expect(header.getByRole('link', { name: 'Saved products (1)', exact: true })).toBeVisible()
  for (const width of [1440, 375]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await header.screenshot({ path: `artifacts/storefront-header/saved-${width}.png` })
  }
  await page.getByRole('button', { name: 'Unsave Studio Headphones', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No saved products yet.' })).toBeVisible()
  await expect(header.getByRole('link', { name: 'Saved products (0)', exact: true })).toBeVisible()
})

