import { expect, test } from '@playwright/test'

const store = '/store/everyday-studio'

test('storefront discovery follows the reference layout without a filter sidebar', async ({ page }) => {
  await page.goto(store)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/Your space\.\s*Your style\./)
  await expect(page.getByRole('complementary', { name: 'Catalog filters' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Filters', exact: true })).toHaveCount(0)
  await expect(page.locator('canvas')).toHaveCount(0)
  await expect(page.locator('#top-picks')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'THE EVERYDAY EDIT' })).toHaveCount(0)
  await page.setViewportSize({ width: 1440, height: 900 })
  const grid = page.getByRole('region', { name: 'Products' })
  expect(await grid.evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(7)
  await expect(grid.getByRole('article')).toHaveCount(7)
  await expect(page.getByRole('button', { name: 'Sort products by price' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Featured', exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Shop by category' }).getByRole('link')).toHaveCount(20)
  const sectionOrder = await page.locator('#categories, #flash-deals, #top-searches').evaluateAll(elements => elements.map(element => element.id))
  expect(sectionOrder).toEqual(['categories', 'flash-deals', 'top-searches'])
  await expect(page.getByRole('region', { name: 'Flash Deals' }).getByRole('link', { name: /^View deal for / })).toHaveCount(6)
  await page.getByRole('button', { name: 'Discover more', exact: true }).click()
  await expect(grid.getByRole('article')).toHaveCount(14)
  await expect(page.getByRole('button', { name: 'All products shown' })).toBeDisabled()
  await page.reload()
  await expect(grid.getByRole('article')).toHaveCount(14)
  await page.getByRole('button', { name: 'Next collection', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/Less noise\.\s*More you\./)
  await page.getByRole('button', { name: 'Previous collection', exact: true }).click()
  await page.getByRole('navigation', { name: 'Shopping shortcuts' }).getByRole('link', { name: 'Categories', exact: true }).click()
  await expect(page).toHaveURL(/#categories$/)
  await expect(page.getByRole('region', { name: 'Shop by category' })).toBeInViewport()
  await page.getByRole('region', { name: 'Shop by category' }).getByRole('link', { name: 'Electronics', exact: true }).click()
  await expect(grid.getByRole('article')).toHaveCount(3)
  await expect(grid).toContainText('Studio Headphones')
  await page.goto(store)
  await page.getByRole('navigation', { name: 'Shopping shortcuts' }).getByRole('link', { name: 'Shopee', exact: true }).click()
  await expect(page).toHaveURL(/channel=shopee/)
  await expect(grid.getByRole('article')).toHaveCount(7)
})
test('flash deals show reference styling, preserve the countdown and expire', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-19T05:00:00Z') })
  await page.goto(store)
  const deals = page.getByRole('region', { name: 'Flash Deals', exact: true })
  await expect(deals.getByRole('link', { name: /^View deal for / })).toHaveCount(6)
  await expect(deals.locator('del')).toHaveCount(6)
  await expect(deals.getByRole('progressbar')).toHaveCount(6)
  const timer = deals.getByRole('timer')
  const initial = await timer.innerText()
  await page.clock.fastForward(2000)
  await expect(timer).not.toHaveText(initial)
  const end = await page.evaluate(() => sessionStorage.getItem('smartomni:everyday-studio:demo-deal-end'))
  await page.reload()
  expect(await page.evaluate(() => sessionStorage.getItem('smartomni:everyday-studio:demo-deal-end'))).toBe(end)
  await deals.getByRole('link', { name: 'View deal for Wireless Mouse', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Wireless Mouse')
  await page.goto(store)
  await page.clock.fastForward(4 * 3600 * 1000)
  await expect(deals).toContainText('DEALS ENDED')
  await expect(deals.getByRole('progressbar')).toHaveCount(0)
})

